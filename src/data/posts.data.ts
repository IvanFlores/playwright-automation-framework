/** Small data factories. Prefer factories over inline literals in tests. */
const uniqueSuffix = () => `${Date.now()}-${Math.floor(Math.random() * 1e4)}`;

export type Post = { title: string; body: string; userId: number };

export const buildPost = (overrides: Partial<Post> = {}): Post => ({
  title: `Post ${uniqueSuffix()}`,
  body: 'Generated by test data factory',
  userId: 1,
  ...overrides,
});
